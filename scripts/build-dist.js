/*
 * Generates the HOSTED (production) manifest from the dev manifest.
 *
 *   node scripts/build-dist.js   -> writes dist/MacTrace.manifest.xml
 *
 * The dev manifest (manifest.xml) points at https://localhost:3100 and is used
 * with the local server (npm start / npm run autostart). The generated one
 * points at GitHub Pages, so end users need no local server, Node, or
 * certificates — just the manifest in Excel's wef folder (see the installer,
 * scripts/build-installer.sh).
 *
 * The two manifests have DIFFERENT GUIDs so both versions can be sideloaded
 * side by side on the same machine.
 */
const fs = require("fs");
const path = require("path");

// Single source of truth for where the add-in is hosted. If the GitHub repo
// is ever renamed, update this — but note that every already-installed user
// keeps a manifest with the old URL baked in, so rename BEFORE distributing.
const PAGES_BASE =
  "https://hubertszymanowski.github.io/MacTrace---Excel-add-in-for-MacOS";

// Stable identity of the HOSTED add-in. Never reuse the dev manifest's GUID.
const PROD_GUID = "7c6db1de-8fdd-4f9d-96fe-825965b4275e";

const DEV_BASE = "https://localhost:3100";
const DEV_GUID = "d4a8f2e1-7b3c-4e9a-9c2d-1f6b8a5e3c47";

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "manifest.xml");
const OUT_DIR = path.join(ROOT, "dist");
const OUT = path.join(OUT_DIR, "MacTrace.manifest.xml");

let xml = fs.readFileSync(SRC, "utf8");

if (!xml.includes(DEV_BASE) || !xml.includes(DEV_GUID)) {
  console.error(
    "manifest.xml no longer contains the expected dev base URL or GUID.\n" +
      "Update DEV_BASE / DEV_GUID in scripts/build-dist.js to match."
  );
  process.exit(1);
}

xml = xml.split(DEV_BASE).join(PAGES_BASE);
xml = xml.split(DEV_GUID).join(PROD_GUID);

// The hosted add-in's support link should be the project page, not the pane.
xml = xml.replace(
  /<SupportUrl DefaultValue="[^"]*" \/>/,
  '<SupportUrl DefaultValue="' + PAGES_BASE + '/" />'
);

// Mark the file as generated.
xml = xml.replace(
  /^(<\?xml[^>]*\?>\n)/,
  "$1<!-- GENERATED by scripts/build-dist.js — do not edit. Edit manifest.xml and run: npm run build:dist -->\n"
);

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, xml);
console.log("Wrote " + path.relative(ROOT, OUT));
console.log("  Hosted at: " + PAGES_BASE);
console.log("  Add-in ID: " + PROD_GUID + " (dev manifest keeps " + DEV_GUID + ")");
